"""Stage 5: what if the stock does not follow Black-Scholes at all?

A dealer sells a 3-month at-the-money call at 20% vol and delta-hedges it
with the Black-Scholes delta at 20%. The stock is generated by one of three
models, all with the same average variance (20% vol), so the dealer has the
*level* of vol right and only the *model* wrong:

  GBM      constant vol: the Black-Scholes world (the control)
  Heston   vol is random, mean-reverting and negatively correlated with
           the stock
  Merton   constant vol plus about one downward jump a year

Questions:
  1. What do the P&L tails look like under each model?
  2. Does hedging more often help? (GBM: yes, 1/sqrt(N). Others: no.)
  3. Where do the losses come from? (Heston: realised variance on the
     path. Merton: the one big move.)
  4. What should the dealer have charged? (The implied-vol smile.)

Model equations: hedging/paths.py.

Run from the project folder:

    python3 experiments/stage5_wrong_model.py

Writes charts and a summary table to results/.
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from scipy.stats import kurtosis, skew  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from hedging import bs  # noqa: E402
from hedging.hedge import delta_hedge  # noqa: E402
from hedging.paths import simulate_gbm, simulate_heston, simulate_merton  # noqa: E402

OUT = ROOT / "results"

# ---- Set-up --------------------------------------------------------------
S0, K, T, r, SIGMA, MU = 100.0, 100.0, 0.25, 0.03, 0.20, 0.08
FINE_STEPS = 504                  # ~hourly
DAILY = 63
N_PATHS = 20_000
SEED = 2026

# Heston: starts at, and reverts to, 20% vol. Feller condition holds
# (2 kappa theta = 0.24 > xi^2 = 0.16), so variance rarely touches zero.
HESTON = dict(v0=SIGMA**2, kappa=3.0, theta=SIGMA**2, xi=0.4, rho=-0.7)

# Merton: one jump a year on average, mean -8%, std 8% (in log terms). The
# diffusive vol is lowered so that total variance is still 20%^2:
#     sigma_d^2 + lam (m^2 + s^2) = SIGMA^2   ->   sigma_d = 16.5%
LAM, JUMP_MEAN, JUMP_STD = 1.0, -0.08, 0.08
SIGMA_D = float(np.sqrt(SIGMA**2 - LAM * (JUMP_MEAN**2 + JUMP_STD**2)))

FREQUENCIES = {12: "~weekly", 21: "every 3 days", 63: "daily",
               126: "twice daily", 252: "4x daily", 504: "~hourly"}
STRIKES = ((90.0, "put"), (100.0, "call"), (110.0, "call"))
SMILE_STRIKES = np.arange(80.0, 121.0, 5.0)
SMILE_PATHS = 40_000

# ---- Chart style (same as stage 2) ---------------------------------------
SURFACE, INK, INK_2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
BLUE, ORANGE, AQUA = "#2a78d6", "#eb6834", "#1baf7a"
plt.rcParams.update({
    "figure.facecolor": SURFACE, "axes.facecolor": SURFACE,
    "axes.edgecolor": INK_2, "axes.labelcolor": INK_2, "axes.titlecolor": INK,
    "xtick.color": INK_2, "ytick.color": INK_2, "text.color": INK,
    "axes.spines.top": False, "axes.spines.right": False,
    "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6,
    "axes.titlesize": 12, "axes.titleweight": "bold", "font.size": 10,
    "legend.frameon": False,
})
COLORS = {"GBM": BLUE, "Heston": ORANGE, "Merton": AQUA}


def simulate_all(mu: float, n_steps: int, n_paths: int, seed: int) -> dict:
    """Paths from the three models with the same drift and average variance."""
    common = dict(T=T, n_steps=n_steps, n_paths=n_paths, seed=seed, antithetic=True)
    return {
        "GBM": simulate_gbm(S0, mu, SIGMA, **common),
        "Heston": simulate_heston(S0, mu, **HESTON, **common)[0],
        "Merton": simulate_merton(S0, mu, SIGMA_D, LAM, JUMP_MEAN, JUMP_STD, **common),
    }


def expected_shortfall(pnl: np.ndarray, level: float = 0.01) -> float:
    """Average of the worst `level` fraction of outcomes."""
    worst = np.sort(pnl)[: max(1, int(level * len(pnl)))]
    return float(worst.mean())


def tail_stats(res) -> dict:
    return dict(mean=res.mean, std=res.std, skew=float(skew(res.pnl)),
                kurt=float(kurtosis(res.pnl)),           # excess: normal = 0
                p01=float(np.percentile(res.pnl, 1)),
                es01=expected_shortfall(res.pnl),
                worst=float(res.pnl.min()),
                corr=float(np.corrcoef(res.pnl, res.gamma_pnl)[0, 1]))


def model_smile() -> dict:
    """Implied vol by strike under each model.

    Monte Carlo price of the out-of-the-money option under the risk-neutral
    drift (mu = r), inverted through Black-Scholes. This assumes investors
    demand no extra premium for vol or jump risk, so it is the *fair* smile.
    Only the price at T matters, so GBM and Merton need a single step.
    """
    common = dict(T=T, n_paths=SMILE_PATHS, seed=SEED + 1, antithetic=True)
    terminal = {
        "GBM": simulate_gbm(S0, r, SIGMA, n_steps=1, **common)[:, -1],
        "Heston": simulate_heston(S0, r, **HESTON, n_steps=DAILY, **common)[0][:, -1],
        "Merton": simulate_merton(S0, r, SIGMA_D, LAM, JUMP_MEAN, JUMP_STD,
                                  n_steps=1, **common)[:, -1],
    }
    smile = {}
    for name, S_T in terminal.items():
        vols = []
        for strike in SMILE_STRIKES:
            kind = "put" if strike < S0 else "call"
            price = np.exp(-r * T) * bs.payoff(S_T, strike, kind).mean()
            vols.append(bs.implied_vol(price, S0, strike, T, r, kind=kind))
        smile[name] = np.array(vols)
    return smile


def main() -> None:
    OUT.mkdir(exist_ok=True)
    paths = simulate_all(MU, FINE_STEPS, N_PATHS, SEED)

    # 1 + 2. Hedge every model at every frequency with the BS delta at 20%.
    results = {name: {n: delta_hedge(P[:, :: FINE_STEPS // n], K, T, r, SIGMA)
                      for n in FREQUENCIES}
               for name, P in paths.items()}
    stats = {name: {n: tail_stats(res) for n, res in by_n.items()}
             for name, by_n in results.items()}

    # 4. The smile, and what selling other strikes at a flat 20% earns.
    smile = model_smile()
    strike_rows = []
    for strike, kind in STRIKES:
        for name, P in paths.items():
            res = delta_hedge(P[:, :: FINE_STEPS // DAILY], strike, T, r, SIGMA,
                              kind=kind)
            fair_vol = float(smile[name][list(SMILE_STRIKES).index(strike)])
            strike_rows.append(dict(
                strike=strike, kind=kind, model=name, mean=res.mean,
                se=res.std / np.sqrt(N_PATHS), premium=res.premium,
                fair_vol=fair_vol))

    write_table(stats, strike_rows, smile)
    chart_distributions(results)
    chart_risk_vs_frequency(stats)
    chart_attribution(paths, results)
    chart_smile(smile)

    print(f"Merton diffusive vol: {SIGMA_D:.4f}")
    for name in paths:
        for n in (DAILY, FINE_STEPS):
            s = stats[name][n]
            print(f"{name:<7} N={n:>3} mean={s['mean']:+.3f} std={s['std']:.3f} "
                  f"skew={s['skew']:+.2f} kurt={s['kurt']:.1f} "
                  f"1%={s['p01']:.2f} ES1%={s['es01']:.2f} worst={s['worst']:.2f}")
    for name, vols in smile.items():
        print(name, " ".join(f"{k:.0f}:{v:.1%}" for k, v in zip(SMILE_STRIKES, vols)))


def write_table(stats, strike_rows, smile) -> None:
    premium = float(bs.price(S0, K, T, r, SIGMA))
    lines = [
        "# Stage 5 results: hedging with the wrong model",
        "",
        f"Short 3-month ATM call, S0=K={S0:.0f}, r={r:.0%}, sold and hedged with "
        f"Black-Scholes at {SIGMA:.0%} (premium {premium:.4f}). Real-world drift "
        f"{MU:.0%}, {N_PATHS:,} paths per model. All three models have the same "
        f"average variance ({SIGMA:.0%} vol).",
        "",
        f"- **Heston**: kappa={HESTON['kappa']:g}, theta=v0={HESTON['theta']:g}, "
        f"xi={HESTON['xi']:g}, rho={HESTON['rho']:g}",
        f"- **Merton**: {LAM:g} jump/year, log jump ~ N({JUMP_MEAN:g}, {JUMP_STD:g}²), "
        f"diffusive vol {SIGMA_D:.1%}",
        "",
        "## Hedged P&L by model and rebalancing frequency",
        "",
        "Excess kurtosis: a normal distribution has 0. ES 1% is the average of "
        "the worst 1% of paths.",
        "",
        "| Model | Rebalances | Mean | Std | Skew | Excess kurtosis | 1st pct "
        "| ES 1% | Worst path | corr with gamma attribution |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name, by_n in stats.items():
        for n, s in by_n.items():
            lines.append(
                f"| {name} | {n} | {s['mean']:+.4f} | {s['std']:.4f} | "
                f"{s['skew']:+.2f} | {s['kurt']:.1f} | {s['p01']:.3f} | "
                f"{s['es01']:.3f} | {s['worst']:.2f} | {s['corr']:.3f} |")
    lines += [
        "",
        "## The fair smile under each model",
        "",
        f"Implied vol of the Monte Carlo price ({SMILE_PATHS:,} paths, "
        "risk-neutral drift, no risk premium). The GBM row should be flat at "
        "20%; its deviation shows the Monte Carlo error.",
        "",
        "| Model | " + " | ".join(f"K={k:.0f}" for k in SMILE_STRIKES) + " |",
        "|---|" + "---:|" * len(SMILE_STRIKES),
    ]
    for name, vols in smile.items():
        lines.append(f"| {name} | " + " | ".join(f"{v:.1%}" for v in vols) + " |")
    lines += [
        "",
        "## Selling other strikes at a flat 20% (daily hedging)",
        "",
        "| Option | Model | Fair implied vol | Premium at 20% | Mean hedged P&L "
        "| Std error |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for row in strike_rows:
        lines.append(
            f"| {row['strike']:.0f} {row['kind']} | {row['model']} | "
            f"{row['fair_vol']:.1%} | {row['premium']:.4f} | {row['mean']:+.4f} | "
            f"{row['se']:.4f} |")
    (OUT / "stage5_summary.md").write_text("\n".join(lines) + "\n")


def chart_distributions(results) -> None:
    fig, ax = plt.subplots(figsize=(7.5, 4.6))
    bins = np.linspace(-14, 3, 171)
    for name, by_n in results.items():
        res = by_n[DAILY]
        ax.hist(res.pnl, bins=bins, histtype="step", lw=1.8, color=COLORS[name],
                density=True, label=f"{name}: std {res.std:.2f}, "
                                    f"worst 1% average {expected_shortfall(res.pnl):.1f}")
    ax.set_yscale("log")
    ax.set_xlabel("Hedged P&L at expiry")
    ax.set_ylabel("Density (log scale)")
    ax.set_title("Same average vol, daily hedging: the model decides the left tail",
                 loc="left")
    ax.legend(loc="upper left")
    fig.tight_layout()
    fig.savefig(OUT / "stage5_pnl_distributions.png", dpi=160)
    plt.close(fig)


def chart_risk_vs_frequency(stats) -> None:
    fig, ax = plt.subplots(figsize=(7.5, 4.6))
    ns = np.array(list(FREQUENCIES))
    for name, by_n in stats.items():
        stds = [by_n[n]["std"] for n in ns]
        ax.plot(ns, stds, "o-", color=COLORS[name], ms=8, mec=SURFACE, mew=2,
                lw=1.5, label=name)
        ax.annotate(f"{stds[-1]:.2f}", (ns[-1], stds[-1]), color=COLORS[name],
                    textcoords="offset points", xytext=(9, -3))
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xticks(ns)
    ax.set_xticklabels([str(n) for n in ns])
    ax.minorticks_off()
    yticks = [0.15, 0.3, 0.5, 1.0, 2.0]
    ax.set_yticks(yticks)
    ax.set_yticklabels([f"{y:g}" for y in yticks])
    ax.set_xlim(ns[0] * 0.85, ns[-1] * 1.35)
    ax.set_xlabel("Rebalances over the option's life (log scale)")
    ax.set_ylabel("Std of hedged P&L (log scale)")
    ax.set_title("Trading more often only removes the risk the stock can hedge",
                 loc="left")
    ax.legend(loc="lower left")
    fig.tight_layout()
    fig.savefig(OUT / "stage5_risk_vs_frequency.png", dpi=160)
    plt.close(fig)


def chart_attribution(paths, results) -> None:
    """Where the losses come from under each wrong model (daily hedging)."""
    step = FINE_STEPS // DAILY
    sample = slice(0, 5000)
    fig, axes = plt.subplots(1, 2, figsize=(10.5, 4.6), sharey=True)

    # Heston: P&L against the vol the path actually realised.
    daily = np.log(paths["Heston"][:, ::step])
    realised_vol = np.sqrt((np.diff(daily, axis=1)**2).sum(axis=1) / T)
    pnl = results["Heston"][DAILY].pnl
    axes[0].scatter(100 * realised_vol[sample], pnl[sample], s=7, color=ORANGE,
                    alpha=0.35, linewidths=0)
    grid = np.linspace(0.08, 0.45, 50)
    vega0 = float(bs.vega(S0, K, T, r, SIGMA))
    axes[0].plot(100 * grid, vega0 * (SIGMA - grid), color=INK_2, lw=1.2, ls="--")
    axes[0].text(44.5, vega0 * (SIGMA - 0.45) - 1.6, "vega × (20% − realised)",
                 color=INK_2, ha="right")
    axes[0].set_xlabel("Realised vol of the path (%)")
    axes[0].set_ylabel("Hedged P&L at expiry")
    axes[0].set_title("Heston: a bet on the path's realised vol", loc="left")

    # Merton: P&L against the largest single daily move on the path.
    daily = np.diff(np.log(paths["Merton"][:, ::step]), axis=1)
    biggest = daily[np.arange(len(daily)), np.abs(daily).argmax(axis=1)]
    pnl = results["Merton"][DAILY].pnl
    axes[1].scatter(100 * biggest[sample], pnl[sample], s=7, color=AQUA,
                    alpha=0.35, linewidths=0)
    axes[1].set_xlabel("Largest one-day log return on the path (%)")
    axes[1].set_title("Merton: one gap decides the outcome", loc="left")
    for ax in axes:
        ax.axhline(0, color=INK_2, lw=0.8)
    fig.tight_layout()
    fig.savefig(OUT / "stage5_attribution.png", dpi=160)
    plt.close(fig)


def chart_smile(smile) -> None:
    fig, ax = plt.subplots(figsize=(7.5, 4.6))
    for name, vols in smile.items():
        ax.plot(SMILE_STRIKES, 100 * vols, "o-", color=COLORS[name], ms=7,
                mec=SURFACE, mew=1.5, lw=1.5, label=name)
    ax.axvline(S0, color=INK_2, lw=1, ls="--")
    ax.text(S0 + 0.5, 15.2, "spot", color=INK_2)
    ax.set_xlabel("Strike")
    ax.set_ylabel("Fair implied vol, 3 months (%)")
    ax.set_title("The smile is the price of the risk delta-hedging leaves behind",
                 loc="left")
    ax.legend(loc="upper right")
    fig.tight_layout()
    fig.savefig(OUT / "stage5_smile.png", dpi=160)
    plt.close(fig)


if __name__ == "__main__":
    main()
